import { createRequire } from 'node:module';
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { afterEach, expect, it, vi } from 'vitest';
import type { WorkbookDocument } from '@open-design/contracts/runtime/workbook';
import { gridWorkbook } from '../../src/components/embedded/workbook/grid-model';
import { workbookGridEdits } from '../../src/components/embedded/workbook/grid-edits';
import { workbookFormattingBridge } from '../../src/components/embedded/workbook/grid-format';
const require = createRequire(realpathSync(fileURLToPath(new URL('../../node_modules/@univerjs/preset-sheets-core/package.json', import.meta.url))));
const core = require('@univerjs/core') as typeof import('@univerjs/presets');
const { FUniver } = require('@univerjs/core/facade') as typeof import('@univerjs/presets');
const sheets = require('@univerjs/sheets') as typeof import('@univerjs/preset-sheets-core');
require('@univerjs/sheets/facade');
const closers: (() => void)[] = [];
afterEach(() => { closers.splice(0).reverse().forEach(close => close()); vi.unstubAllGlobals(); });
it('executes genuine pinned formatting commands, creates sparse style plans and keeps normal undo', async () => {
  const English = require('@univerjs/preset-sheets-core/locales/en-US');
  const univer = new core.Univer({ locale: core.LocaleType.EN_US, locales: { [core.LocaleType.EN_US]: English.default ?? English } }); closers.push(() => univer.dispose()); univer.registerPlugin(sheets.UniverSheetsPlugin);
  const api = FUniver.newAPI(univer);
  const model: WorkbookDocument = { version: 1, date1904: false, activeSheetId: 's', styles: [{ font: { name: 'Calibri', size: 11 } }], features: { charts: 0, drawings: 0, externalLinks: 0, macros: false, signed: false }, sheets: [{ id: 's', name: 'Sheet', visibility: 'visible', rowCount: 100, columnCount: 26, cells: [{ row: 1, column: 1, kind: 'number', value: 10000 }], merges: [], rowDimensions: [], columnDimensions: [], frozenRows: 0, frozenColumns: 0 }] };
  const book = api.createWorkbook(gridWorkbook(model, 'format-test', 'Format').data), sheet = book.getActiveSheet(); book.setEditable(true);
  sheet.setActiveRange(sheet.getRange(1, 1, 1, 1));
  univer.__getInjector().get(core.IUniverInstanceService).focusUnit(book.getId()); const initial = book.save();
  const postMessage = vi.fn(), parent = { postMessage }, handlers = new Set<(event: MessageEvent) => void>();
  vi.stubGlobal('window', { parent, location: { origin: 'http://fixture.invalid' }, addEventListener: (_: string, fn: (event: MessageEvent) => void) => handlers.add(fn), removeEventListener: (_: string, fn: (event: MessageEvent) => void) => handlers.delete(fn) });
  const scope = { projectId: '11111111-1111-4111-8111-111111111111', controllerId: '22222222-2222-4222-8222-222222222222', blocked: false };
  const bridge = workbookFormattingBridge(api, () => scope); closers.push(bridge.dispose);
  const message = (action: unknown, selectionKey = 's:1:1:1:1', overrides = {}) => handlers.forEach(fn => fn({ source: parent, origin: 'http://fixture.invalid', data: { type: 'studio:workbook-format', projectId: scope.projectId, controllerId: scope.controllerId, selectionKey, action }, ...overrides } as unknown as MessageEvent));
  expect(postMessage.mock.lastCall?.[0]).toMatchObject({ selected: true });
  message({ property: 'bold', value: true });
  expect(postMessage.mock.lastCall?.[0]).toMatchObject({ error: null, bold: true });
  expect(workbookGridEdits(model, 'a'.repeat(64), initial, book.save()).styles).toEqual([{ sheetId: 's', row: 1, column: 1, bold: true }]);
  await api.undo(); expect(workbookGridEdits(model, 'a'.repeat(64), initial, book.save()).styles).toBeUndefined();
  message({ property: 'fontSize', value: 22.5 });
  expect(postMessage.mock.lastCall?.[0]).toMatchObject({ fontSize: 22.5 });
  expect(workbookGridEdits(model, 'a'.repeat(64), initial, book.save()).styles).toEqual([{ sheetId: 's', row: 1, column: 1, fontSize: 22.5 }]);
  await api.undo(); expect(workbookGridEdits(model, 'a'.repeat(64), initial, book.save()).styles).toBeUndefined();
  message({ property: 'italic', value: true }); message({ property: 'fontColor', value: '#123456' }); message({ property: 'fillColor', value: '#abcdef' });
  const plan = workbookGridEdits(model, 'a'.repeat(64), initial, book.save());
  expect(plan.edits).toEqual([]); expect(plan.styles).toEqual([{ sheetId: 's', row: 1, column: 1, italic: true, fontColor: 'FF123456', fillColor: 'FFabcdef' }]);
  message({ property: 'fontColor', value: null }); message({ property: 'fillColor', value: null });
  expect(sheet.getRange(1, 1).getCellStyleData()?.cl).toEqual({ rgb: 'rgb(0, 0, 0)' });
  expect(sheet.getRange(1, 1).getCellStyleData()?.bg).toEqual({ rgb: 'rgba(0,0,0,0)' });
  expect(core.getColorStyle({ rgb: 'rgb(0, 0, 0)' })).toBe('#000000');
  const reset = workbookGridEdits(model, 'a'.repeat(64), initial, book.save());
  expect(reset.styles?.[0]).toMatchObject({ fontColor: null, fillColor: null });
  const saved = book.save();
  message({ property: 'bold', value: true }, 'stale');
  message({ property: 'bold', value: true }, 's:1:1:1:1', { origin: 'http://other.invalid' });
  scope.blocked = true; message({ property: 'bold', value: true });
  expect(book.save()).toEqual(saved);
  scope.blocked = false; book.setEditable(false); message({ property: 'bold', value: true }); expect(book.save()).toEqual(saved);
  expect(postMessage).toHaveBeenCalled();
});
