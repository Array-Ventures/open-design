import { afterEach, expect, it } from 'vitest';
import { Univer, LocaleType, ICommandService, IUniverInstanceService, UniverInstanceType, type Workbook, type IWorkbookData } from '@univerjs/core';
import { UniverSheetsPlugin, RemoveSheetCommand, SetWorksheetNameCommand } from '@univerjs/sheets';
import { FUniver } from '@univerjs/core/facade';
import '@univerjs/sheets/facade';
import English from '@univerjs/sheets/locale/en-US';
import { workbookDocumentSchema } from '@open-design/contracts/runtime/workbook';
import models from '../fixtures/workbook-restored-style-models.json';
import { gridWorkbook } from '../../src/components/embedded/workbook/grid-model';
import { seedWorkbookStructureIdentity } from '../../src/components/embedded/workbook/grid-structure-identity';
import { captureWorkbookSourceDeletion, stampWorkbookSourceDeletion, associateWorkbookSourceDeletion, workbookSourceDeletionBaselineIdentity } from '../../src/components/embedded/workbook/sheet-delete-context';
import { bindWorkbookSourceSnapshot } from '../../src/components/embedded/workbook/source-snapshot-binding';
import { checkedWorkbookSaveAcknowledgement } from '../../src/components/embedded/workbook/save-provenance';
import { workbookGridPlan } from '../../src/components/embedded/workbook/grid-plan';
import { appendRestoredSheetModel, restoreHistoricalCellGuards } from '../../src/components/embedded/workbook/grid-restored-sheet';

// These strict public models were generated by the actual source reader from
// the styled B.xlsx / source-preserving Delete+style C.xlsx proof. The separate
// scratch ZIP qualification exercises real bytes; this fixture is not an asset
// authorization or HTTP receipt proof.
const scope = { viewerId: 'owned-person', projectId: '11111111-1111-4111-8111-111111111111', fileName: 'book.xlsx', draftId: '22222222-2222-4222-8222-222222222222' };
const sourceSha256 = 'a'.repeat(64), targetSha256 = 'b'.repeat(64);
const closers: (() => void)[] = [];
afterEach(() => closers.splice(0).reverse().forEach(close => close()));
async function fixture() {
  const historical = workbookDocumentSchema.parse(models.historical), current = workbookDocumentSchema.parse(models.current);
  const initial = seedWorkbookStructureIdentity(gridWorkbook(historical, `${scope.projectId}:${scope.fileName}`, 'Workbook').data as IWorkbookData, sourceSha256);
  const univer = new Univer({ locale: LocaleType.EN_US, locales: { [LocaleType.EN_US]: English } });
  closers.push(() => univer.dispose()); univer.registerPlugin(UniverSheetsPlugin);
  const api = FUniver.newAPI(univer), book = api.createWorkbook(initial);
  const instances = univer.__getInjector().get(IUniverInstanceService), commands = univer.__getInjector().get(ICommandService);
  instances.focusUnit(book.getId());
  const before = book.save();
  book.getSheetBySheetId('1')!.getRange('A1').setValue(20);
  book.getSheetBySheetId('1')!.getRange('A1').setFontSize(22.25);
  commands.syncExecuteCommand(SetWorksheetNameCommand.id, { unitId: book.getId(), subUnitId: '1', name: 'Current survivor' });
  book.getSheetBySheetId('2')!.getRange('A1').setValue(19);
  let deletion = captureWorkbookSourceDeletion(scope, { version: 1, source: { model: historical, sourceSha256 }, acknowledged: before, desired: book.save(), pending: null }, '2');
  stampWorkbookSourceDeletion(instances.getUnit<Workbook>(book.getId(), UniverInstanceType.UNIVER_SHEET)!.getSheetBySheetId('2')!, deletion.descriptor);
  commands.syncExecuteCommand(RemoveSheetCommand.id, { unitId: book.getId(), subUnitId: '2' });
  const acknowledged = book.save();
  const operationId = crypto.randomUUID(), renderId = crypto.randomUUID();
  const acknowledgement = checkedWorkbookSaveAcknowledgement({ id: operationId, projectId: scope.projectId, fileName: scope.fileName, renderId, state: 'applied', sourceSha256, targetSha256, actualSha256: targetSha256, sourceVersionId: 'historical-B', versionId: 'current-C' },
    { operationId, projectId: scope.projectId, fileName: scope.fileName, renderId, preparationId: crypto.randomUUID(), plan: { sourceSha256, edits: [] } }, targetSha256);
  deletion = associateWorkbookSourceDeletion(deletion, acknowledgement);
  const binding = bindWorkbookSourceSnapshot(scope, { model: current, sourceSha256: targetSha256 }, acknowledged, acknowledgement)!;
  await api.undo();
  const desired = book.save();
  const context = { scope: { ...scope }, deletions: [deletion], sourceOwner: { scope: { ...scope }, acknowledgement, binding } };
  return { historical, current, deletion, acknowledged, desired, context,
    plan: () => workbookGridPlan(current, targetSha256, acknowledged, desired, context) };
}
it('derives restored desired19 while keeping current survivor20 and historical compact style ownership', async () => {
  const f = await fixture(), before = structuredClone({ current: f.current, acknowledged: f.acknowledged, desired: f.desired });
  expect(f.historical.styles[1]!.font).toMatchObject({ bold: true, size: 11 });
  expect(f.current.styles[1]!.font?.size).toBe(22.25);
  const plan = f.plan();
  expect(plan.sheets).toEqual([
    { sheetId: '1', name: 'Current survivor', origin: 'source' },
    { sheetId: '2', name: 'Restored', origin: 'restore', template: { versionId: 'historical-B', versionSha256: sourceSha256 }, baselineIdentity: workbookSourceDeletionBaselineIdentity(f.deletion) },
  ]);
  expect(plan.edits).toEqual([{ sheetId: '2', cell: { row: 0, column: 0, style: 1, kind: 'number', value: 19 } }]);
  expect(f.desired.sheets['1']!.cellData![0]![0]!.v).toBe(20);
  expect(f.current).toEqual(before.current); expect(f.acknowledged).toEqual(before.acknowledged); expect(f.desired).toEqual(before.desired);
});
it('requires an exact scoped selected context and an explicit historical receipt association', async () => {
  const f = await fixture();
  for (const mutate of [
    () => { f.context.scope.viewerId = 'someone-else'; },
    () => { delete f.deletion.receiptAssociation; },
    () => { f.deletion.descriptor.token = crypto.randomUUID(); },
  ]) {
    const saved = structuredClone(f.context); mutate();
    expect(f.plan).toThrow(); Object.assign(f.context, saved); f.context.deletions = [f.deletion];
    Object.assign(f.deletion, saved.deletions[0]);
  }
});
it('merges inherited row and column style closure without rewriting source model ordinals', async () => {
  const f = await fixture(), model = structuredClone(f.current), context = structuredClone(f.deletion);
  context.baseline.sheet.rowDimensions.push({ index: 0, style: 1 });
  context.baseline.sheet.columnDimensions.push({ index: 0, style: 1 });
  const selected = appendRestoredSheetModel(model, context);
  expect(selected.cells[0]!.style).toBe(2);
  expect(selected.rowDimensions[0]!.style).toBe(2); expect(selected.columnDimensions[0]!.style).toBe(2);
  expect(model.styles[2]!.font).toMatchObject({ bold: true, size: 11 });
  expect(model.styles[1]!.font?.size).toBe(22.25);
  expect(workbookDocumentSchema.safeParse(model).success).toBe(true);
});
it('translates only the exact historical cell across validated structural origins and refuses mismatched styles', async () => {
  const f = await fixture(), model = structuredClone(f.current);
  appendRestoredSheetModel(model, f.deletion);
  const contexts = new Map([['2', f.deletion]]);
  const base = { sourceSha256: targetSha256, edits: [{ sheetId: '2', cell: { row: 1, column: 0, kind: 'number' as const, value: 19, style: 2 } }],
    structure: [{ sheetId: '2', sourceRows: 100, sourceColumns: 26, rows: [null, ...Array.from({ length: 100 }, (_, index) => index)], columns: Array.from({ length: 26 }, (_, index) => index) }] };
  expect(restoreHistoricalCellGuards(structuredClone(base), model, contexts).edits[0]!.cell.style).toBe(1);
  const wrong = structuredClone(base); wrong.edits[0]!.cell.style = 1;
  expect(() => restoreHistoricalCellGuards(wrong, model, contexts)).toThrow('style guard');
  const fresh = structuredClone(base); fresh.edits[0]!.cell.row = 0;
  expect(() => restoreHistoricalCellGuards(fresh, model, contexts)).toThrow('no historical');
});
